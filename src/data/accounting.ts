// Отметки на скринах заданы в процентах от картинки: x слева, y сверху (центр кружка).
// mx и my — место отметки на телефоне, если там показан другой фрагмент скрина.
// crop — фрагмент для телефона [x, y, ширина, высота] в процентах: целиком широкий скрин на 390 px не читается,
// поэтому показываем главное, а весь скрин открывается по нажатию (промт, раздел 5).
// where — строка над скрином: адрес портала или программа, в которой снят скрин.

export type Mark = { x: number; y: number; text: string; mx?: number; my?: number };
export type Shot = { name: string; w: number; h: number; full: number; alt: string; where: string; crop?: [number, number, number, number]; marks?: Mark[] };

const PORTAL = 'client.axiomco.io';
const img = (name: string, w: number, h: number, where: string, alt: string, o: { marks?: Mark[]; crop?: Shot['crop']; full?: number } = {}): Shot =>
  ({ name, w, h, where, alt, full: o.full ?? 2400, marks: o.marks, crop: o.crop });
export const src = (s: Shot, w: number) => `/img/accounting/${s.name}-${w}.webp`;
export const srcset = (s: Shot) => `${src(s, s.w)} ${s.w}w, ${src(s, s.full)} ${s.full}w`;

