// Небольшой типограф для русского текста по правилам Бюро.
// Ставит неразрывные пробелы там, где перенос строки мешает читать.

const NBSP = ' ';

// Короткие слова, которые не должны оставаться в конце строки.
const SHORT_WORDS = [
  'а', 'в', 'во', 'и', 'к', 'ко', 'с', 'со', 'у', 'о', 'об', 'от', 'до', 'за', 'из', 'на', 'не', 'ни',
  'по', 'но', 'же', 'то', 'мы', 'вы', 'он', 'их', 'её', 'ее', 'без', 'для', 'при', 'про', 'над', 'под',
  'как', 'что', 'или', 'чем', 'это', 'все', 'всё',
];

// Частицы, которые не должны начинать строку.
const PARTICLES = ['бы', 'ли', 'же'];

const shortRe = new RegExp(`(^|[\\s(«„"—])(${SHORT_WORDS.join('|')}) `, 'giu');
const particleRe = new RegExp(` (${PARTICLES.join('|')})(?=[\\s.,!?;:]|$)`, 'giu');

export function t(input: string): string {
  if (!input) return input;
  let s = input;
  // Два прохода: «и в», «а не» и подобные цепочки.
  s = s.replace(shortRe, (_m, pre, w) => `${pre}${w}${NBSP}`);
  s = s.replace(shortRe, (_m, pre, w) => `${pre}${w}${NBSP}`);
  s = s.replace(particleRe, (_m, p) => `${NBSP}${p}`);
  // Тире не начинает строку.
  s = s.replace(/ —/g, `${NBSP}—`);
  // Число и следующее за ним слово или единица: 40 дней, 3,55 млрд IDR, 1 клик.
  s = s.replace(/(\d[\d,.%+]*) (?=[^\s\d])/g, `$1${NBSP}`);
  // «млрд IDR», «млн IDR» не разрываем.
  s = s.replace(/(млрд|млн|тыс\.) (IDR|USD|THB|AED)/g, `$1${NBSP}$2`);
  // Диапазон чисел не разрываем: 3–5 дней.
  s = s.replace(/(\d)–(\d)/g, '$1–\u2060$2');
  // № и число.
  s = s.replace(/№ (\d)/g, `№${NBSP}$1`);
  return s;
}
